import { readFile, writeFile } from 'node:fs/promises'
import { createHash } from 'node:crypto'
const root = new URL('../', import.meta.url)
const digest = bytes => createHash('sha256').update(bytes).digest('hex')
const pins = {}, data = {}
for (const name of ['province-boundaries.json', 'yunnan-boundary.json', 'places.json', 'national-places.json']) {
  const bytes = await readFile(new URL('src/data/' + name, root))
  // Canonical JSON hashes survive LF/CRLF checkout transformations; content still fails closed.
  data[name] = JSON.parse(bytes.toString().replace(/^\uFEFF/, ''))
  pins[name] = digest(JSON.stringify(data[name]))
}
const old = data['places.json'], added = data['national-places.json'], provinces = data['province-boundaries.json'].features
const ids = new Set(), provinceIds = new Set(provinces.map(p => p.properties.provinceId))
for (const place of [...old, ...added]) {
  if (ids.has(place.id) || !place.coordinateSource.url || place.coordinateSystem !== 'WGS84' || !Array.isArray(place.coordinates) || place.coordinates.length !== 2 || !place.coordinates.every(Number.isFinite)) throw new Error(`Invalid reviewed place: ${place.id}`)
  ids.add(place.id)
}
for (const place of added) if (!provinceIds.has(place.mapId) || place.mapId !== place.regionId || !['classic', 'local'].includes(place.discoveryTier)) throw new Error(`Invalid region/tier: ${place.id}`)
if (old.length !== 43 || provinces.length !== 34 || new Set(old.map(p => p.regionId)).size !== 16) throw new Error('Legacy coverage changed')
const versionHash = digest(JSON.stringify([pins['places.json'], pins['national-places.json']])).slice(0, 8)
const legacyVersions = JSON.parse(await readFile(new URL('src/data/catalogue-releases.json', root), 'utf8'))
for (const releasedIds of Object.values(legacyVersions)) if (!releasedIds.every(id => ids.has(id))) throw new Error('A published identity is missing')
const manifest = { schemaVersion: 1, hashAlgorithm: 'sha256-canonical-json', catalogueVersion: `national${ids.size}-${versionHash}`, validationVersion: 'national-20260907-b6918bc0', counts: { provinces: 34, regions: 49, publicPlaces: ids.size }, pins, legacyVersions }
const json = JSON.stringify(manifest, null, 2)
const outputs = [[new URL('src/data/catalogue-manifest.json', root), json + '\n'], [new URL('../shanhai-api/src/catalogue-manifest.ts', root), '// Generated by shanhai-app/scripts/build-catalogue-manifest.mjs; do not edit.\nexport const catalogueManifest = ' + json + ' as const\n']]
for (const [path, text] of outputs) {
  if (process.argv.includes('--check')) { if (await readFile(path, 'utf8') !== text) throw new Error(`Stale catalogue manifest: ${path}`) }
  else await writeFile(path, text)
}
console.log(`${manifest.catalogueVersion}: ${manifest.counts.publicPlaces} controlled public places`)
