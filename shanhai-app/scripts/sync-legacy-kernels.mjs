/**
 * Mechanical compatibility extraction, not a second implementation.
 * The built app imports checked-in modules only; legacy files are required only
 * when explicitly refreshing or checking this migration boundary.
 */
import { createHash } from 'node:crypto'
import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'

const check = process.argv.includes('--check')
if (process.argv.slice(2).some(arg => arg !== '--check')) throw new Error('Usage: node scripts/sync-legacy-kernels.mjs [--check]')
const sourceRoot = new URL('../../output/shanhai-lijiang-records/', import.meta.url)
const targetRoot = new URL('../src/generated/', import.meta.url)
const sources = [
  { source: 'backup-codec.js', target: 'backup-kernel.js', factory: 'createBackupKernel' },
  { source: 'local-store.js', target: 'local-store-kernel.js', factory: 'createLocalStoreKernel' },
]

function replaceExactlyOnce(source, old, replacement) {
  if (source.split(old).length !== 2) throw new Error(`Legacy boundary changed: expected exactly one ${JSON.stringify(old)}`)
  return source.replace(old, replacement)
}

function extract(raw, specification) {
  // Normalize transport line endings, not program tokens or algorithms.
  let body = raw.replaceAll('\r\n', '\n')
  body = replaceExactlyOnce(body, '(function (root) {\n', '')
  body = replaceExactlyOnce(body, '})(globalThis);', '')
  // ES modules are already strict; directives are illegal with the injected
  // destructured parameter lists and carry no extra semantics here.
  body = replaceExactlyOnce(body, "  'use strict';\n", '')
  if (specification.factory === 'createBackupKernel') {
    body = replaceExactlyOnce(body, 'root.ShanhaiBackup = Object.freeze(', 'return Object.freeze(')
  } else {
    body = replaceExactlyOnce(body, 'root.createShanhaiLocalStore = function createShanhaiLocalStore(', 'return (function createShanhaiLocalStore(')
    if (!body.trimEnd().endsWith('  };')) throw new Error('Local-store factory terminator changed')
    body = body.trimEnd().slice(0, -4) + '  })(options);\n'
  }
  body = body.replaceAll('root.ShanhaiPlaces', 'catalogue').replaceAll('root.ShanhaiBackup', 'backup')
    .replaceAll('root.', 'platform.')
    .replaceAll('new Blob(', 'new platform.Blob(')
    .replaceAll('instanceof Blob', 'instanceof platform.Blob')
    .replaceAll('new TextEncoder(', 'new platform.TextEncoder(')
  if (/\broot\b|globalThis|new Function\b|\beval\s*\(/.test(body)) throw new Error('Unexpected ambient dependency in extracted kernel')
  const signature = specification.factory === 'createBackupKernel'
    ? '{ catalogue, platform }'
    : '{ catalogue, backup, platform }, options = {}'
  const hash = createHash('sha256').update(raw).digest('hex')
  return `// GENERATED by scripts/sync-legacy-kernels.mjs. Do not edit manually.\n// Source: output/shanhai-lijiang-records/${specification.source}\n// Source SHA-256: ${hash}\n// Algorithms retained verbatim; only factory/platform bindings are extracted.\nexport function ${specification.factory}(${signature}) {\n${body.trimEnd()}\n}\n`
}

if (!check) await mkdir(targetRoot, { recursive: true })
let stale = false
for (const specification of sources) {
  const raw = await readFile(new URL(specification.source, sourceRoot), 'utf8')
  const generated = extract(raw, specification)
  const target = new URL(specification.target, targetRoot)
  if (check) {
    let existing
    try { existing = await readFile(target, 'utf8') } catch (cause) { if (cause.code !== 'ENOENT') throw cause }
    if (existing?.replaceAll('\r\n', '\n') !== generated) {
      console.error(`STALE ${fileURLToPath(target)}; run node scripts/sync-legacy-kernels.mjs`)
      stale = true
    } else console.log(`FRESH ${specification.target}`)
  } else {
    await writeFile(target, generated, 'utf8')
    console.log(`GENERATED ${specification.target}`)
  }
}
if (stale) process.exitCode = 1
